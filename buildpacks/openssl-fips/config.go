package opensslfips

import (
	"bytes"
	"text/template"
)

// opensslConfig mirrors /etc/ssl/openssl.cnf from the openssl-config-fipshardened
// package, but includes fipsmodule.cnf by absolute path so the provider can
// live in a layer instead of /etc/ssl.
//
// fipsmodule.cnf itself is written only by `openssl fipsinstall -pedantic`
// when the provider package is built; section 11.1 of the security policy
// forbids editing it, so this file only references it. The module is found
// through OPENSSL_MODULES rather than a "module" key in that file for the
// same reason.
var opensslConfig = template.Must(template.New("openssl.cnf").Parse(`# Generated by the fckfips/openssl-fips buildpack.
#
# Loads only the {{.Module}} and the base provider
# (encoders and decoders, no cryptography), and makes fips=yes the default
# property query, so every algorithm fetched without an explicit provider
# comes from the validated module. config_diagnostics makes a provider that
# fails its self tests or integrity check a fatal error rather than a silent
# fallback.
config_diagnostics = 1
openssl_conf = openssl_init
# Node.js reads this section name unless started with --openssl-shared-config.
nodejs_conf = openssl_init

.include {{.FIPSModuleConf}}

[openssl_init]
providers = provider_sect
alg_section = algorithm_sect
ssl_conf = ssl_module

[provider_sect]
fips = fips_sect
base = base_sect

[base_sect]
activate = 1

[algorithm_sect]
default_properties = fips=yes

[ssl_module]
system_default = tls_policy

# TLS 1.2 is the lowest version allowed for federal systems (NIST SP 800-52 Rev. 2)
[tls_policy]
MinProtocol = TLSv1.2
`))

func renderConfig(module, fipsModuleConf string) ([]byte, error) {
	var b bytes.Buffer
	err := opensslConfig.Execute(&b, struct{ Module, FIPSModuleConf string }{module, fipsModuleConf})
	return b.Bytes(), err
}
